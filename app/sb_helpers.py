def _panel_dup_spans(txt: str):
    """全部「雷同类」词根命中（两族正则合并，按**命中起点**从左到右排序）。

    合并的意义：否定语境只看命中点**之前**的文字，所以真正的判定顺序必须与人在句子里
    读到它们的顺序一致 —— 否则「未达面板雷同阈值，但动作与构图高度雷同」会被前一条
    的否定词误伤（跨子句继承否定）。排序后逐条判定，命中即返回，避免这类串扰。
    """
    spans = []
    for _rx in _PANEL_DUP_RES:
        spans.extend(_rx.finditer(txt or ""))
    spans.sort(key=lambda m: (m.start(), -m.end()))
    return spans


def _panel_dup_next_clause(txt: str, pos: int) -> str:
    """取 pos 之后**紧邻的下一个子句**（跳过标点，遇下一个标点即止）。

    同义族的「弱化语境」判定要用（见 _PANEL_DUP_SYN_SOFT_TAIL 的说明）。
    只取**紧邻**子句，不跨句继承 —— 实测整句窗口会把真缺陷一起吞掉
    （「…构图高度雷同，仅微小表情位移…」里的「仅」落在后一子句）。
    """
    seg = txt[pos:]
    i, n = 0, len(seg)
    while i < n and seg[i] in _PANEL_DUP_SEP:
        i += 1
    j = i
    while j < n and seg[j] not in _PANEL_DUP_SEP:
        j += 1
    return seg[i:j]


def _panel_dup_hit(txt: str) -> bool:
    """判定文本是否含**未被否定**的「面板雷同 / 面板重复」类表述。

    覆盖两族判语（2026-10-12 t8 扩面，见 _PANEL_DUP_SYN_RES 注释）：
      · 带前缀族：「面板/九宫格/格间 + 雷同/重复」；
      · 同义族  ：4 条精确子模式（姿态族 / 复合族 / 单一族 / 强度族）。

    否定语境判定（见 _PANEL_DUP_NEG_STRONG 的说明）：
      · 前 6 字命中弱否定词 → 视为达标结论；
      · 前 8 字命中强否定短语 → 视为达标结论；
      · 词根**中间的修饰位**恰好是一个纯否定词（「格间**无**雷同」「构图**不**重复」）
        → 同样是达标结论（注意：修饰位为空串的「面板雷同」是**真缺陷**，不能误伤）；
      · 都不命中 → 真缺陷，返回 True。

    同义族另加一层**弱化语境**排除（见 _PANEL_DUP_SYN_SOFT 的说明）；
    带前缀族不受该层影响，行为与扩面前逐字一致。
    """
    for m in _panel_dup_spans(txt):
        near6 = txt[max(0, m.start() - 6):m.start()]
        # 遇句子边界截断：只保留**本句内**的否定语境，绝不继承上一句
        _cut = -1
        for _sep in _PANEL_DUP_SEP:
            _pos = near6.rfind(_sep)
            if _pos > _cut:
                _cut = _pos
        if _cut >= 0:
            near6 = near6[_cut + 1:]
        if any(n in near6 for n in _PANEL_DUP_NEG_WEAK):
            continue
        if any(n in near6 for n in _PANEL_DUP_NEG_STRONG):
            continue
        # 词根之间的修饰位若**恰好**是一个纯否定词 → 达标结论（如「格间无雷同」）。
        # 只认「整段修饰位就是否定词」这一种：空白修饰位（「面板雷同」）是真缺陷，
        # 「无规律重复」这种带实词的修饰位也不放过（那不是否定，是缺陷描述）。
        _gap = m.group(0)[len(m.group(1)):len(m.group(0)) - len(m.group(2))].strip()
        if _gap and (_gap in _PANEL_DUP_NEG_WEAK or _gap in _PANEL_DUP_NEG_STRONG):
            continue
        # 同义族专属：VLM 判**通过**时描述轻微瑕疵的句式不判缺陷
        # （带前缀族不走这一层，见 _PANEL_DUP_SYN_SOFT 的说明）。
        if m.re in _PANEL_DUP_SYN_RES:
            if any(w in near6 for w in _PANEL_DUP_SYN_SOFT):
                continue
            if any(w in _panel_dup_next_clause(txt, m.end())
                   for w in _PANEL_DUP_SYN_SOFT_TAIL):
                continue
        return True
    return False


def _sb_heal_comfyui(task_id: str, project: str) -> bool:
    """分镜/资产 worker 里的 ComfyUI 自愈：连续拒连/未出图时自动重启 ComfyUI 进程。

    背景（2026-10-08）：ComfyUI 在「后端超时 → 全局 /interrupt」后可能进入半死状态
    （webserver 仍监听 8188 但执行器被打断），后续镜头 /upload/image 全部 10061 拒连。
    本函数在「该镜头 ComfyUI 未出图且 ComfyUI 不在线」时重启 ComfyUI 并等它就绪，
    让下一镜头（或本镜头重试）能继续，而非让整集镜头全挂。

    返回 True = 已重启且就绪（可继续），False = 重启失败/ComfyUI 仍离线（按离线处理）。
    全程 fail-open，不抛异常。
    """
    global _comfyui_heal_count
    try:
        _comfyui_heal_count = getattr(globals(), "_comfyui_heal_count", 0) + 1
        logger.warning(
            "[自愈] 镜头 ComfyUI 未出图且离线，自动重启 ComfyUI（第 %d 次，项目=%s，任务=%s）",
            _comfyui_heal_count, project, task_id)
        ok = comfyui_client.restart_comfyui(wait_sec=180, poll_sec=3.0)
        if ok:
            logger.info("[自愈] ComfyUI 重启成功，继续分镜生成")
        else:
            logger.warning("[自愈] ComfyUI 重启后仍未就绪，本镜头继续按离线处理")
        return ok
    except Exception as e:  # noqa: BLE001
        logger.warning("[自愈] ComfyUI 重启异常（按离线处理）：%s", e)
        return False


def _sb_structural_defect(gate) -> bool:
    """该镜的质检结论是否含**结构性缺陷**（软放行必须跳过它们）。

    判定文本 = reason + label + critical_issues（三者任一命中即算）。
    gate 非 dict / 缺字段都返回 False（退化为「可软放行」，不改变既有行为）。
    """
    if not isinstance(gate, dict):
        return False
    parts = [str(gate.get("reason") or ""), str(gate.get("label") or "")]
    for x in (gate.get("critical_issues") or []):
        parts.append(str(x))
    txt = " ".join(parts)
    # 面板雷同类：词根正则 + 否定语境排除（不能用字面词条，原因见 _PANEL_DUP_RE 注释）
    if _panel_dup_hit(txt):
        return True
    return any(k in txt for k in _SB_STRUCTURAL_DEFECT_KEYWORDS)

