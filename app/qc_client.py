def _apply_image_objective(verdict: dict, image_path: str, cfg: dict) -> dict:
    """G9/O1 图片客观层（零模型依赖，与视频/音频客观层同构）。

    全黑/全白/纯色（像素 stddev < 阈值）→ fatal 计入 critical_issues、blocked=True；
    长宽比异常 → 非 fatal 计入 issues。AI 层失败也会透出（不因 AI 不可用漏掉黑图）。

    **幂等**：二次复核会对「第二份 AI 结论」再跑一次本函数，因此这里先摘掉上一次
    追加过的客观层 issues 再重新追加（否则重复调用会让 issues 越加越多）。
    抽成独立函数的原因就是复核链路要复用同一份客观判定口径。
    """
    verdict = verdict or {}
    try:
        obj = image_objective(image_path, cfg)
    except Exception as e:  # noqa: BLE001  客观层失败不阻断质检主流程
        logger.warning("图片客观层执行失败（忽略）：%s: %s", type(e).__name__, e)
        return verdict
    obj_fatal = list(obj.get("critical_issues") or [])
    obj_issues = list(obj.get("issues") or [])
    verdict["objective"] = obj
    verdict["objective_fatal"] = obj_fatal
    verdict["objective_issues"] = obj_issues
    base_issues = [x for x in (verdict.get("issues") or []) if x not in obj_issues]
    if obj_issues:
        verdict["issues"] = base_issues + obj_issues
    else:
        verdict["issues"] = base_issues
    if obj_fatal:
        base_crit = [x for x in (verdict.get("critical_issues") or []) if x not in obj_fatal]
        verdict["critical_issues"] = base_crit + obj_fatal
        verdict["blocked"] = True
        verdict["passed"] = False
        verdict["score"] = min(int(verdict.get("score") or 0), 50)
    return verdict


def _image_verdict_accepted(verdict: dict) -> bool:
    """内容层是否「通过」。⚠️ 只看 ok/accepted —— skipped（质检未开启）不算通过。"""
    return bool(verdict) and bool(verdict.get("ok")) and bool(verdict.get("accepted"))


def _recheck_image_verdict(ep: dict, prompt: str, image_paths: list, cfg: dict,
                           first: dict, image_path: str, style_norm: str) -> dict:
    """图片质检「二次复核」：同一张图再判一次，任一判过即放行。

    背景（实测）：同一张分镜图 + 同一组设定图 + temperature=0，重复 4 次送检得到
    score = 85 / 78 / 45 / 92（通过率 2/4）；同一轮还会出现「景别完美符合」
    与「景别严重不符（接近全景）」两个互斥结论。判官抖动**会直接变成一次 GPU 重画**
    （1-2 分钟），而复核只用 2-5 秒 —— 交换比约 1:20，故默认开启。

    决策（单向放宽，只在「首次判不过」时触发）：
      · 客观层致命（黑图/纯色）→ **不复核**（确定性证据，复核无意义）；
      · 复核调用抛异常 → 沿用首次结论（绝不把接口抖动变成放行）；
      · 复核判过 → 返回复核结论（并在 recheck 里留档首次结论，便于复盘）；
      · 两次都判不过 → 返回首次结论（保持「只有一处结论」的原有行为）。
    """
    info = {"used": True, "first_score": first.get("score"),
            "first_accepted": bool(first.get("accepted"))}
    if first.get("objective_fatal"):
        info["used"] = False
        info["skip_reason"] = "客观层致命（黑图/纯色）为确定性证据，无需复核"
        first["recheck"] = info
        return first
    try:
        second = _run_vision(ep, prompt, image_paths, cfg)
    except Exception as e:  # noqa: BLE001  复核失败绝不能把「判不过」变成「判过」
        logger.warning("图片二次复核调用失败，沿用首次结论：%s: %s", type(e).__name__, e)
        info["error"] = str(e)
        first["recheck"] = info
        return first
    second = _apply_style_gate(second, style_norm)
    second = _apply_image_objective(second, image_path, cfg)
    info["second_score"] = second.get("score")
    info["second_accepted"] = bool(second.get("accepted"))
    info["disagreed"] = bool(first.get("accepted")) != bool(second.get("accepted"))
    if _image_verdict_accepted(second):
        info["outcome"] = "复核放行（首次判不过判定为判官抖动）"
        logger.info("图片质检二次复核放行：首次 score=%s(%s) → 复核 score=%s(%s)",
                    first.get("score"), first.get("reason"),
                    second.get("score"), second.get("reason"))
        # 首次结论留档：复核放行不代表首次说的问题不存在，排查时仍需可见
        second["recheck_first"] = {
            "score": first.get("score"), "reason": first.get("reason"),
            "issues": (first.get("issues") or [])[:3],
            "critical_issues": (first.get("critical_issues") or [])[:3],
        }
        second["recheck"] = info
        return second
    info["outcome"] = "两次均判不通过"
    first["recheck"] = info
    return first


def check_image(image_path: str, shot_desc: str = "", cfg: dict = None,
                override: dict = None, style: str = "",
                ref_images: list = None,
                prev_shot_desc: str = "", prev_shot_ref: str = "",
                blocking_ref: str = "", blocking_spec: str = "") -> dict:
    """单张图片质检。永不抛异常：失败时返回 ok=False 并带 error。
    override 仅用于「测试连通性」临时传参，不落盘。
    style：目标风格串（用户与总控敲定），用于「风格达标」判定；为空则不做风格检测。
    ref_images：设定参考图 [(label, path), ...]（也可以是 {"label","path"} dict）——
      生成侧用的那几张角色 / 物品 / 场景设定图。给了就一并送检，让模型能**逐个核对
      「画面里的角色 / 物品是否与设定一致、有没有变形」**，而不是凭想象判。
      受 cfg["image_ref_compare"]（默认 True）控制；不存在的文件与重复图（同一张被多个
      槽位复用）自动跳过。
    prev_shot_desc / prev_shot_ref（2026-09-25 需求 J / P1）：**上一镜**的文字描述与画面
      路径。给了就追加「跨镜连续性」判定口径，并把上一镜画面一并送检，让模型能真正比对
      背景结构 / 光照方向 / 服化道是否漂移。两者都为空时**完全不加这部分**（零行为变更），
      避免模型凭「上一镜」这几个字臆造一条不一致缺陷。
    blocking_ref（2026-09-27）：3D 导演台站位/机位**构图基准图**（无面人偶预演图）。
      给了就追加「构图基准核对」口径，让质检真正判定「这镜有没有照着 3D 站位/机位出图」。
      送检顺序为 [成品图, 基准图, ...设定图]，与 :func:`build_blocking_note` 的编号一致；
      该图**不占**设定图名额（``MAX_REF_IMAGES`` 只约束设定图）。"""
    cfg = cfg or _empty_config()
    if not cfg.get("enabled"):
        return {"ok": False, "skipped": True, "reason": "质检总开关未开启"}
    if not cfg.get("image_enabled"):
        return {"ok": False, "skipped": True, "reason": "图片质检开关未开启"}
    ep = resolve_endpoint(cfg, override)
    if not (ep["base_url"] and ep["api_key"] and ep["model"]):
        return {"ok": False, "skipped": True, "reason": "质检接口未配置（base_url/api_key/model）"}
    if not image_path or not os.path.isfile(image_path):
        return {"ok": False, "skipped": False, "error": f"图片不存在：{image_path}"}
    style_norm = str(style or "").strip()
    prompt = (cfg.get("image_prompt") or DEFAULT_IMAGE_PROMPT).replace(
        "{shot_desc}", shot_desc or "（无）").replace(
        "{pass_score}", str(cfg.get("pass_score", 70))).replace(
        "{style}", style_norm or "（未指定）")
    prompt = prompt + WATERMARK_EXEMPT_NOTE + CRITICAL_RULE_NOTE + FRAMING_TOLERANCE_NOTE + MANNEQUIN_DISTINCTION_NOTE + STORYBOARD_GRID_ANALYSIS_NOTE
    if style_norm:
        prompt = prompt + STYLE_CHECK_NOTE.replace("{style}", style_norm)
    # ---- 角色资产的人物性别一致性（2026-09-28）：拿不到性别时整段不追加 ----
    if _should_check_gender(shot_desc):
        prompt = prompt + GENDER_CHECK_NOTE
    # ---- 构图基准图（3D 导演台站位/机位）：不占设定图名额，单独一条口径 ----
    # ⚠️⚠️ 2026-09-30 实测紧急关闭（注：2026-10-01 起该开关默认 True；此处 fallback False 仅防御配置键缺失）：
    #     把 3D 基准图（灰/蓝色**无面人偶**预演图）与成品图一起送进视觉模型，会**严重污染**
    #     判定 —— 同一张合格图实测：不传基准图 score=88 通过；传了基准图 score=35 拒绝，
    #     且模型开始**凭空捏造**缺陷（「白色双眼」「彩色球体水系法术」「逻辑自相矛盾」）。
    #     更早那批「画面内容为蓝色无面人偶」「提交图为构图预演人偶」的荒谬判定也是同一原因：
    #     模型把送检的第 2 张人偶图当成了待检成品图。这正是分镜 2 连续 6 次、分镜 1~7
    #     反复「质检不过→重试」的**真正元凶**（并非出图质量问题）。
    #     基准图仍照常用于**出图**（构图约束有效）；只是不再作为质检输入。
    #     如确需核对构图，必须走**独立的一次专用调用**，绝不能与成品图同批送检。
    _blk_cmp_on = bool(cfg.get("image_blocking_ref_compare", False))
    # ⛔️ 不再把「无面人偶预演图」送进视觉质检（2026-10-01 定论）。
    # 实测：同一张合格分镜图，不送基准图 score=88 通过；送了 score=35 拒绝 ——
    # 污染来自**图像本身**（灰蓝人偶、纯色底被当成画面内容），怎么加强提示词口径都压不住。
    # 解法：改送 `blocking_spec`（te_3d_director.blocking_spec_text 生成的**确定性**文字规格：
    # 人数 / 左右顺序 / 景别 / 机位），既保住「有没有照构图出图」的核对能力，又零视觉污染。
    # 模式二分（2026-10-05）：blocking_spec 非空 → **文字规格模式**（不送任何基准图，
    # 图片序列 = 待检图 + 设定图，设定图从第 2 张数起）；仅当没给文字规格、却真的传了
    # 基准图路径时，才走旧「第 2 张=基准图」模式（build_blocking_note，设定图从第 3 张起）。
    blocking_used = False       # 本镜启用「构图核对」（文字规格或基准图二选一）
    blocking_img_used = False   # True = 真的把基准图作为第 2 张图送检（旧模式）
    if _blk_cmp_on and str(blocking_spec or "").strip():
        prompt = prompt + "\n" + str(blocking_spec).strip()
        blocking_used = True
    elif _blk_cmp_on and str(blocking_ref or "").strip() and os.path.isfile(blocking_ref):
        # 兼容旧调用（只传基准图路径、无文字规格）
        blocking_used = True
        blocking_img_used = True
    # ---- 设定一致性核对：把生成时用的参考图一并送检 ----
    # ⚠️ 2026-10-02 修复：这里曾被写成三参 cfg.get("image_ref_compare",
    #    "image_blocking_ref_compare", True) → dict.get 最多 2 个参数，只要
    #    ref_images 非空就抛 TypeError（而生产三处调用都在传 ref_images），
    #    导致有设定图的分镜质检 100% 失败。回落到两参原口径。
    # ⚠️ 本开关与上面 :2130 的 image_blocking_ref_compare 是**两件事**，别混：
    #    那个只控制 3D 构图核对（文字规格 / 旧基准图）是否生效，默认 True（2026-10-01 起）。
    ref_list = []
    if ref_images and cfg.get("image_ref_compare", True):
        seen = {os.path.abspath(image_path)}
        if blocking_img_used and blocking_ref:
            seen.add(os.path.abspath(blocking_ref))
        for item in ref_images:
            if isinstance(item, dict):
                label = item.get("label") or item.get("name") or ""
                path = item.get("path") or item.get("file") or item.get("image")
            elif isinstance(item, (list, tuple)) and len(item) >= 2:
                label, path = item[0], item[1]
            else:
                continue
            if not path or not os.path.isfile(path):
                continue
            ap = os.path.abspath(path)
            if ap in seen:      # 同一张图被多个槽位复用（如主角色=次要角色）不重复送
                continue
            seen.add(ap)
            ref_list.append((label, path))
        ref_list = ref_list[:MAX_REF_IMAGES]
    # ---- 跨镜连续性（P1，2026-09-25）：仅在提供了上一镜信息时启用 ----
    # ⚠️ 放在 ref_list 之后：上一镜画面要作为**额外参考图**送检（模型才能真正比对），
    #    而 ref_list 有 MAX_REF_IMAGES 上限，故先装满设定图、再追加上一镜，
    #    且**不占用设定图名额**（设定图的一致性判定优先级更高）。
    _prev_used = False
    if prev_shot_desc or prev_shot_ref:
        prompt = prompt + CONTINUITY_NOTE
        _prev_lines = []
        if prev_shot_desc:
            _prev_lines.append(f"上一镜信息：{prev_shot_desc}")
        if prev_shot_ref and os.path.isfile(prev_shot_ref):
            _prev_lines.append("上一镜画面：见随附的「上一镜参考」图")
            _prev_used = True
        if _prev_lines:
            prompt = prompt + "\n" + "\n".join(_prev_lines) + "\n"
    if blocking_img_used:
        prompt = prompt + build_blocking_note(len(ref_list))
    elif blocking_used:
        # 文字规格模式：本次没送基准图，文案不得再提「第 2 张=构图基准图」，
        # 设定图从第 2 张数起（与下方 build_ref_consistency_note(start=2) 编号一致）
        prompt = prompt + build_blocking_spec_note(len(ref_list))
    if ref_list:
        prompt = prompt + build_ref_consistency_note(ref_list, start=3 if blocking_img_used else 2)
    image_paths = [image_path]
    if blocking_img_used and blocking_ref:
        # 判空防护（2026-10-05）：空字符串路径进 encode_image_data_url 会抛
        # FileNotFoundError，让整次质检变成 interface_fault（而非「跳过基准图」）
        image_paths.append(blocking_ref)
    image_paths.extend(p for _l, p in ref_list)
    if _prev_used:
        # 上一镜画面追加在**最后**（顺序与 prompt 里「见随附的上一镜参考图」对应）
        image_paths.append(prev_shot_ref)
    try:
        verdict = _run_vision(ep, prompt, image_paths, cfg)
    except Exception as e:  # noqa: BLE001
        logger.warning(f"图片质检调用失败：{e}")
        # P0-2：显式标注「接口级故障」——调用根本没拿到模型判定（鉴权 401/403/404、
        # 超时、网络抖动等），**不是**「图片内容不合格」。上层闸门据此 fail-open
        # （放行已出图资产 + 响亮告警），而不是把 ComfyUI 已出好的图按内容不合格丢弃。
        return {"ok": False, "skipped": False, "error": str(e),
                "api_attempts": getattr(e, "attempts", 1),
                "retryable": getattr(e, "retryable", None),
                "interface_fault": True}
    verdict = _apply_style_gate(verdict, style_norm)
    # 把「带了几张设定图」透出来，便于前端/体检确认该能力真的生效（而不是静默没带）
    verdict["ref_images_used"] = len(ref_list)
    if blocking_used:
        # 透出「本镜构图核对已启用」（键名沿用旧名；2026-10-01 起文字规格模式下
        # 并不随图送基准图，仅旧基准图模式才是真的带图），便于确认开关/渲染链路真的生效
        verdict["blocking_ref_used"] = True
    if ref_list:
        verdict["ref_labels"] = [str(l)[:60] for l, _p in ref_list]
    # G9/O1 图片客观层（零模型依赖，与视频/音频客观层同构）：
    # 全黑/全白/纯色（像素 stddev < 阈值）→ fatal 计入 critical_issues、blocked=True；
    # 长宽比异常 → 非 fatal 计入 issues。AI 层失败也会透出（不因 AI 不可用漏掉黑图）。
    verdict = _apply_image_objective(verdict, image_path, cfg)
    # ★ 二次复核（判官自洽性检查）：首次判不过时用**同一张图**再判一次，任一判过即放行。
    #   实测判官自身抖动极大（同一张图 score 45/78/85/92），而每次「判不过」都会触发
    #   一次 GPU 重画 —— 复核成本 2-5 秒 vs 重画 1-2 分钟。开关 cfg["image_qc_recheck"]。
    if not _image_verdict_accepted(verdict) and cfg.get("image_qc_recheck", True):
        verdict = _recheck_image_verdict(ep, prompt, image_paths, cfg, verdict,
                                         image_path, style_norm)
    return verdict


