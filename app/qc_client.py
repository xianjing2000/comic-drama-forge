# 背景：写剧本层（novel_to_script.REWRITE_RULES 第 9/10 条 + edit_reason 字段）
# 已按 92 镜短片的拆解口径约束了镜头语言克制 / 剪辑动机 / 视觉锚点道具回环。
# 本组纯函数在**剧本质检**侧做同口径的客观复检，但全部走**软告警**：
# 只写进 issues 提示，不命中 CRITICAL_ISSUE_KEYWORDS、不进 structure/logic
# critical 桶、不直接判 pass=false —— 避免判官抖动与百分比分布误伤重画。
#
# 五层：
#   ① edit_reason 覆盖率：镜头写了剪辑动机的占比，过低说明「为什么切」缺失；
#   ② 镜头语言克制分布：固定机位占比下限 / 特写+全景占比上限（做情绪锚点，非主奏）；
#   ③ 视觉锚点·道具回环：全片出现 ≥2 次的关键道具，其出现镜头是否在
#      description 里落了「视觉锚点」标注或道具状态变化（位置/动作）；
#   ④ 一镜一动作（2026-09-30）：单镜动作节拍数，过多说明模型把多个动作塞进同一镜
#      （成片表现 = 一个分镜不切换、里面演好几件事），违背参考片「一镜一动作」口径；
#   ⑤ 主力景别区间（2026-09-30）：近景/中近景/局部 合计占比下限、大特写/远景/大远景
#      占比上限、「局部」插入镜占比下限，全部对齐参考片 92 镜实测分布。

#: ① edit_reason 覆盖率下限：低于此值提示「剪辑动机缺失」。（样本 < 5 镜时跳过）
EDIT_REASON_COVERAGE_MIN = 0.5
#: ② 固定机位占比下限：92 镜参照 77% 固定，软告警阈值取 60%（克制口径，防运镜滥用）。
LOCKED_OFF_RATIO_MIN = 0.6
#: ② 特写+全景占比上限：参照 92 镜（特写 2 + 全景 3 = 5.4%），软告警阈值取 10%。
ANCHOR_SHOT_RATIO_MAX = 0.10
#: ③ 道具回环的最小出现次数：同一道具出现在 ≥ 该数镜头才认定「回环锚点」。
PROP_RECURRENCE_MIN = 2

#: ④ 一镜一动作（2026-09-30 新增）：单镜动作节拍数上限。参考片 92 镜几乎每镜只有
#: 1 个动作节拍；description 里可数出的动作节拍 ≥ 此值即视为「一镜多动作」。
ACTION_BEATS_MAX = 2
#: ④ 触发阈值：出现「一镜多动作」的镜头数达到该值（或占比 > 20%）时提示，防单镜误伤。
ACTION_BEATS_SHOT_MIN = 3
#: ⑤ 主力景别（参考片 92 镜实测：近景 26% + 中近景 25% + 局部 25% ≈ 76%）。
MAIN_SHOT_TYPES = ("近景", "中近景", "局部")
MAIN_SHOT_RATIO_MIN = 0.55
#: ⑤ 极端景别占比上限：参考片 92 镜里大特写/远景/大远景 = 0%。
EXTREME_SHOT_TYPES = ("大特写", "远景", "大远景")
EXTREME_SHOT_RATIO_MAX = 0.05
#: ⑤「局部」插入镜下限：参考片 25%（只拍手部/道具、不出现完整人脸的插入镜）。
LOCAL_SHOT_RATIO_MIN = 0.10


def _shot_camera_kind(shot: dict) -> str:
    """把镜头 camera 串归一成 {locked, anchor, other} 三档（景别+运镜克制分布用）。

    判定顺序（先锚点特写/全景，再固定，其余算活动运镜）：
    · camera 含「特写」或「全景」→ anchor（情绪锚点，参照 92 镜占比 ~5%）；
    · 否则运镜部分含「固定」或「定格」，或 camera 本身只有景别无机位 → locked；
    · 其余（推/拉/摇/手持/跟/环绕/升降…）→ other。
    """
    cam = str(shot.get("camera") or "").strip()
    if not cam:
        return "other"
    if "特写" in cam or "全景" in cam:
        return "anchor"
    # 固定/定格 视为锁定机位（含「固定中景」「近景固定」等写法）
    if "固定" in cam or "定格" in cam:
        return "locked"
    return "other"


def _shot_action_beats(shot: dict) -> int:
    """数一个镜头里可辨认的「动作节拍」个数（一镜多动作检测用）。

    ⚠️ 口径与**生成期拆镜**（novel_to_script._split_multi_action_row）同源：
    都走 config.count_action_beats / config.ACTION_WORDS（唯一权威表）。
    动作词表若在两处各写一份，会出现「生成期拆了、质检期不认」（或反之），
    拆镜与告警互相打架 —— 与景别白名单曾经五处漂移是同一类缺陷。
    """
    import config as _config
    # ⚠️ 只看 description：它是 schema 里唯一的「谁做了什么」权威字段；
    # visual_detail（补充细节/环境）与 motion（摄影机运动）会把**同一个动作**再写一遍，
    # 合并计数会让「一个动作写三遍」被算成 3 个节拍（实测误报）。
    # 必须与生成期拆镜（_split_multi_action_row 也只切 description）同口径。
    return _config.count_action_beats(str(shot.get("description") or ""))


def _shot_type_of(shot: dict) -> str:
    """本镜景别：优先 shot_type 字段，其次从 camera 复合串里取景别词，最后返回空串。

    ⚠️ 关键词顺序必须是「长词优先」（中近景在近景之前、大特写在大特写之前），
    否则「中近景」会被「近景」抢先命中，分布统计随之失真。
    """
    st = str(shot.get("shot_type") or "").strip()
    if st:
        return st
    cam = str(shot.get("camera") or "")
    for name in ("大特写", "特写", "中近景", "近景", "局部", "中景", "全景", "大远景", "远景"):
        if name in cam:
            return name
    return ""


def _validate_script_92rules(script: dict) -> list:
    """92 镜拆解法五层软告警（2026-09-28 三层 + 2026-09-30 补 ④⑤，全部非 critical）。

    返回的 issues 措辞刻意避开 CRITICAL_ISSUE_KEYWORDS（不用「错位/拼接/变形/崩坏」
    等硬缺陷词），仅作为提示写进 check_script 的 objective issues（进 prompt_quality
    维度扣分，但不触发 critical 短路），符合「软告警口径」。
    """
    issues = []
    shots = [s for s in (script.get("shots") or []) if isinstance(s, dict)]
    n = len(shots)
    if n < 5:  # 样本太少，分布/覆盖率判据无统计意义，跳过全部三层
        return issues

    # ① edit_reason 覆盖率
    with_reason = sum(
        1 for s in shots if str(s.get("edit_reason") or "").strip())
    coverage = with_reason / float(n)
    if coverage < EDIT_REASON_COVERAGE_MIN:
        issues.append(
            f"剪辑动机缺失：仅 {with_reason}/{n} 镜写了 edit_reason（{coverage*100:.0f}% < "
            f"{EDIT_REASON_COVERAGE_MIN*100:.0f}%）。建议按 92 镜口径给每镜补一句「为什么切到这一镜」"
            f"的剪辑动机（20~30 字，写具体叙事功能），作为构图与取舍依据")

    # ② 镜头语言克制分布
    kinds = [_shot_camera_kind(s) for s in shots]
    locked_ratio = kinds.count("locked") / float(n)
    anchor_ratio = kinds.count("anchor") / float(n)
    if locked_ratio < LOCKED_OFF_RATIO_MIN:
        issues.append(
            f"运镜过于活跃：固定机位仅 {kinds.count('locked')}/{n} 镜"
            f"（{locked_ratio*100:.0f}% < {LOCKED_OFF_RATIO_MIN*100:.0f}%）。"
            f"按 92 镜口径运镜应以固定为主（~75%），推/拉/摇/手持/跟随仅在情绪递进或空间转换时用")
    if anchor_ratio > ANCHOR_SHOT_RATIO_MAX:
        issues.append(
            f"特写/全景占比偏高：{kinds.count('anchor')}/{n} 镜"
            f"（{anchor_ratio*100:.0f}% > {ANCHOR_SHOT_RATIO_MAX*100:.0f}%）。"
            f"按 92 镜口径特写与全景只做情绪锚点（各 ≤3%），不宜作为主奏景别")

    # ③ 视觉锚点·道具回环
    from collections import Counter
    prop_shots = Counter()
    prop_shot_ids = {}
    for s in shots:
        sid = str(s.get("shot_id") or "")
        for it in (s.get("items_in_shot") or []):
            it_name = str(it or "").strip()
            if it_name:
                prop_shots[it_name] += 1
                prop_shot_ids.setdefault(it_name, []).append(sid)
    for prop, cnt in prop_shots.items():
        if cnt < PROP_RECURRENCE_MIN:
            continue
        ids = [i for i in prop_shot_ids.get(prop, []) if i]
        # 该道具出现的镜头，description 是否落了「视觉锚点」标注或道具名（状态变化）
        marked = 0
        for s in shots:
            if str(s.get("shot_id") or "") in ids:
                desc = str(s.get("description") or "")
                if "视觉锚点" in desc or prop in desc:
                    marked += 1
        if marked == 0:
            issues.append(
                f"道具回环缺锚点：「{prop}」全片出现 {cnt} 次（镜头 "
                f"{'/'.join(ids[:6])}{'…' if len(ids) > 6 else ''}）但没有任何镜头"
                f" description 写明它的位置/状态变化，也没标「（视觉锚点·第N次）」。"
                f"按 92 镜口径，反复出现的关键道具应作为跨镜头视觉锚点，"
                f"在 description 里写道具的位置与状态变化（如「折叠/展开/递出/攥紧」）")

    # ④ 一镜一动作（2026-09-30 新增）：单镜动作节拍过多 → 模型把多个动作塞进同一镜，
    #    成片表现为「一个分镜不切换、里面却演了好几件事」。参考片口径是一镜只推进一个动作。
    beats = [_shot_action_beats(s) for s in shots]
    over = [i for i, b in enumerate(beats) if b >= ACTION_BEATS_MAX + 1]
    # 双门槛：既要达到最小镜数，占比也要过线 —— 长剧本里 1~2 个镜头多动作不足以说明系统性问题
    _min_shots = max(ACTION_BEATS_SHOT_MIN, int(0.15 * n + 0.5))
    if len(over) >= _min_shots and (len(over) / float(n)) >= 0.15:
        worst = sorted(over, key=lambda i: -beats[i])[:4]   # 只列举真正超标的镜头
        _ids = [str(shots[i].get("shot_id") or (i + 1)) for i in worst]
        issues.append(
            f"一镜多动作：{len(over)}/{n} 镜的动作节拍 ≥{ACTION_BEATS_MAX + 1} 个"
            f"（最多 {max(beats)} 个，如镜头 {'/'.join(_ids)}）。"
            f"按参考片口径每镜只应承载 1 个动作节拍，连续动作必须拆成相邻镜头——"
            f"否则成片会出现「一个分镜不切换、里面演好几件事」")

    # ⑤ 主力景别区间（2026-09-30 新增，对齐参考片 92 镜实测分布：
    #    近景 26% / 中近景 25% / 局部 25% / 中景 17% / 全景 3% / 特写 2% / 大特写·远景·大远景 0%）
    types = [_shot_type_of(s) for s in shots]
    _typed = [x for x in types if x]
    if len(_typed) >= 5:
        _main = sum(1 for x in types if x in MAIN_SHOT_TYPES)
        _ext = sum(1 for x in types if x in EXTREME_SHOT_TYPES)
        _loc = sum(1 for x in types if x == "局部")
        main_ratio = _main / float(len(_typed))
        ext_ratio = _ext / float(len(_typed))
        local_ratio = _loc / float(len(_typed))
        if main_ratio < MAIN_SHOT_RATIO_MIN:
            issues.append(
                f"主力景别偏少：近景/中近景/局部 仅 {_main}/{len(_typed)} 镜"
                f"（{main_ratio*100:.0f}% < {MAIN_SHOT_RATIO_MIN*100:.0f}%）。"
                f"参考片 92 镜里这三类合计约 76%，是叙事主力；"
                f"建议把中景/全景承载的信息收进近景与中近景，补足主力景别")
        if ext_ratio > EXTREME_SHOT_RATIO_MAX:
            issues.append(
                f"大特写/远景/大远景偏多：{_ext}/{len(_typed)} 镜"
                f"（{ext_ratio*100:.0f}% > {EXTREME_SHOT_RATIO_MAX*100:.0f}%）。"
                f"参考片 92 镜这三类一次未用，情绪锚点请只用特写与全景（各 ≤3%）")
        if local_ratio < LOCAL_SHOT_RATIO_MIN:
            issues.append(
                f"「局部」插入镜偏少：仅 {_loc}/{len(_typed)} 镜"
                f"（{local_ratio*100:.0f}% < {LOCAL_SHOT_RATIO_MIN*100:.0f}%）。"
                f"参考片 25% 的镜头是只拍手部/道具、不出现完整人脸的插入镜——"
                f"它能把叙事压到道具上，也是规避人脸崩坏的有效手段，建议适当补足")

    return issues


#: 单镜时长下限/上限：**直接从 config 取**，与生成期（novel_to_script）同源。
#:
#: 历史缺陷一：这里曾自己写一份（1~15 秒）且「镜头数 > 30 就告警」，而剧本生成端是 3~12 秒、
#:   真实剧集单集可达 56 镜 —— 约束互相打架，正常剧本反被判不可执行。
#: 历史缺陷二（2026-09-30）：旧口径 MIN 3s / 静默基准 3s / 描述 +2s / 动作 +1.5s / 高潮 +2s，
#:   使每个镜头地板就是 4~6 秒，而**参考片单镜中位只有 2.08 秒** —— 剪辑点稀疏，
#:   成片观感「一个分镜演半天不切换」。已按参考片重标定到 1.5~8 秒，故这里必须跟着 config 走。
#:
#: ⚠️ 这里校验的是**剧本级**单镜时长；**生成期**已由 ``h3_prompt_kit.segment_durations``
#: 自动切成 ≤4 秒的子段提交给模型（「AI 视频可信窗口约 4 秒」的红线在**单次生成**这一层，
#: 不在剧本这一层）。
SHOT_DURATION_MIN_OK = config.SHOT_DURATION_MIN
SHOT_DURATION_MAX_OK = config.SHOT_DURATION_MAX
#: 超出边界的容差（模型四舍五入 / 台词长度微调）。
#:
#: ⚠️⚠️ 2026-10-02 修复（静默死规则）：容差必须**小于** MIN，否则下限判据
#:   `duration < MIN - TOL` 恒不成立 → 「单镜过短」这条校验**形同虚设**。
#:   历史经过：MIN 从 3.0 重标定到 2.0 时，容差 2.0 未跟着下调 →
#:   `2.0 - 2.0 = 0.0`，连 0.5 秒的镜头都不再报警（0.6 秒的静默镜基准也一并失去保护）。
#:   现按 0.5s 设定（保留浮点/取整宽容，且远小于 MIN）：
#:   · 下限判据 `MIN - TOL = 1.5` → 短于 1.5 秒才报「过短」（有效）
#:   · 上限判据 `MAX + TOL = 8.5` → 长于 8.5 秒才报「过长」（有效）
#: 改 MIN/MAX 时**必须同批复核本值是否仍 < MIN**。
SHOT_DURATION_TOLERANCE = 0.5

#: 每集总时长的**产品口径容差**（2026-09-26 新增）。
#: ⚠️ 上下文：产品口径是「每集 1-2 分钟，最长不超过 3 分钟」
#: （`novel_to_script.EPISODE_MAX_SEC`=180）。本函数原来固定用 60 秒作默认目标、
#: 容差 30%，这在旧口径（一集 1 分钟）下成立，但对新口径会**批量误报** ——
#: 一集 175 秒（合法，在上限内）会被判「与目标 60 秒偏差 192%」。
#:
#: 处置：容差不按「相对目标值的百分比」，而按**是否落在产品允许区间内**判定：
#:   下限 = `EPISODE_MIN_SEC`(60) - 本容差；上限 = `EPISODE_MAX_SEC`(180) + 本容差。
#: 即 60 秒下限放宽到 50 秒、180 秒上限放宽到 190 秒，区间内一律不报。
#: 本容差因此只兜「四舍五入/台词长度微调」级别的小幅越界，不做百分比缩放。
EPISODE_DURATION_TOLERANCE = 10.0


def _episode_duration_bounds() -> tuple:
    """每集时长的产品允许区间 `(lo, hi)`（秒），含容差。

    从 `novel_to_script` 取口径常量（单一事实来源），取不到时退回
    (60, 180) —— 与产品需求「1-2 分钟、最长 3 分钟」一致，**不静默放宽**。
    """
    try:
        import novel_to_script as _nts
        lo = float(getattr(_nts, "EPISODE_MIN_SEC", 60) or 60)
        hi = float(getattr(_nts, "EPISODE_MAX_SEC", 180) or 180)
    except Exception:  # noqa: BLE001 —— 常量不可读不许让质检崩，退回产品默认值
        lo, hi = 60.0, 180.0
    return (max(0.0, lo - EPISODE_DURATION_TOLERANCE),
            hi + EPISODE_DURATION_TOLERANCE)


def _validate_script_feasibility(script: dict, target_duration: int = None) -> list:
    """验证可执行性（阈值与剧本生成端保持一致，见上方常量说明）

    ⚠️ `target_duration` 默认 **None**（2026-09-26 起）：
    空的语义 = 「按产品区间判」（60~180 秒，见 `_episode_duration_bounds`），
    这是生产路径的默认。显式传正数才走旧的「相对偏差 ≤30%」判据。
    """
    issues = []

    shots = script.get("shots", [])
    if not shots:
        issues.append("剧本没有镜头，无法执行")
        return issues

    # 计算总时长
    total_duration = 0
    shot_durations = []
    for i, shot in enumerate(shots):
        if not isinstance(shot, dict):
            continue
        duration = shot.get("duration", 0)
        if not isinstance(duration, (int, float)):
            issues.append(f"镜头 {shot.get('shot_id', f'[{i}]')} 时长无效: {duration}")
            continue

        shot_durations.append(duration)
        total_duration += duration

        # 检查单个镜头时长（留 2 秒容差，避免浮点/取整误报）
        if duration < SHOT_DURATION_MIN_OK - SHOT_DURATION_TOLERANCE:
            issues.append(f"镜头 {shot.get('shot_id', f'[{i}]')} 时长过短: {duration}秒"
                          f"（建议 {SHOT_DURATION_MIN_OK:g}~{SHOT_DURATION_MAX_OK:g} 秒）")
        elif duration > SHOT_DURATION_MAX_OK + SHOT_DURATION_TOLERANCE:
            issues.append(f"镜头 {shot.get('shot_id', f'[{i}]')} 时长过长: {duration}秒"
                          f"（建议 {SHOT_DURATION_MIN_OK:g}~{SHOT_DURATION_MAX_OK:g} 秒）")

    # 检查总时长是否落在**产品允许区间**内（2026-09-26：由「相对 60 秒目标 ±30%」
    # 改为「是否落在 [下限-容差, 上限+容差]」——见 EPISODE_DURATION_TOLERANCE 注释）。
    #
    # ⚠️ target_duration 的语义变更（重要）：
    #   旧口径下它是「一集应有的总时长」（60 秒），判据是相对偏差 ≤30%。
    #   新口径下「一集多长」是一个**区间**（60~180 秒，由拆集逻辑保证），单一目标值
    #   不再成立。因此：
    #     · target_duration 为 None / 0 / 空 → 走**区间判据**（新默认，也是生产路径）；
    #     · 调用方**显式**传了一个正数 → 保留旧的相对偏差判据（不破坏显式调用与历史测试）。
    #   生产路径（app.api_generate_script → check_script）本来就传 duration=60，
    #   那正是旧默认值；改成 None 让区间判据生效，是本次口径切换的关键一步。
    if shot_durations:
        lo, hi = _episode_duration_bounds()
        _explicit = bool(target_duration) and float(target_duration or 0) > 0
        if _explicit:
            # 调用方给了明确目标 → 沿用相对偏差判据（容差 30%，与改造前一致）
            duration_diff = abs(total_duration - target_duration) / float(target_duration)
            if duration_diff > 0.3:
                issues.append(f"总时长 {total_duration}秒 与目标 {target_duration}秒 偏差过大"
                              f"（{duration_diff*100:.0f}%）")
        elif total_duration > hi:
            issues.append(f"总时长 {total_duration}秒 超过单集上限 {hi:g} 秒"
                          f"（产品口径：每集 1~2 分钟、最长 3 分钟）")
        elif total_duration < lo:
            issues.append(f"总时长 {total_duration}秒 低于单集下限 {lo:g} 秒"
                          f"（产品口径：每集 1~2 分钟、最长 3 分钟）")

    # 镜头数量：只卡「少到无法叙事」的下限。不设上限 —— 原文越长镜头越多是设计目标
    #（novel_to_script 按实测约 36 字/镜承载原文，实测单集可达 63 镜）。
    if len(shots) < 3:
        issues.append(f"镜头数量过少（{len(shots)}个），建议至少 5 个镜头")

    return issues


def check_script(script_path: str = None, script_data: dict = None,
                 style: str = "国漫古风", target_duration: int = None,
                 cfg: dict = None, override: dict = None) -> dict:
    """剧本质检：结构+逻辑+风格+提示词质量+可执行性
    
    参数:
        script_path: 剧本文件路径（与script_data二选一）
        script_data: 剧本数据字典
        style: 指定创作风格
        target_duration: 目标总时长（秒）。
            ⚠️ 默认 None（2026-09-26 起）= 按**产品区间**判（每集 60~180 秒）。
            显式传正数则按「与目标的相对偏差 ≤30%」判 —— 兼容历史调用与测试。
        cfg: 质检配置
        override: 临时覆盖配置
    
    返回:
        dict: {
            "ok": bool,           # 质检是否成功执行
            "passed": bool,       # 是否通过质检
            "score": int,         # 综合得分
            "reason": str,        # 一句话结论
            "issues": list,       # 问题列表
            "suggestions": list,  # 改进建议
            "categories": dict,   # 各维度得分
            "skipped": bool,      # 是否跳过
            "error": str,         # 错误信息
        }
    """
    cfg = cfg or _empty_config()
    
    # 检查开关
    if not cfg.get("enabled"):
        return {"ok": False, "skipped": True, "reason": "质检总开关未开启"}
    if not cfg.get("script_enabled"):
        return {"ok": False, "skipped": True, "reason": "剧本质检开关未开启"}
    
    # 检查接口配置
    ep = resolve_endpoint(cfg, override)
    if not (ep["base_url"] and ep["api_key"] and ep["model"]):
        return {"ok": False, "skipped": True, "reason": "质检接口未配置（base_url/api_key/model）"}
    
    # 加载剧本数据
    if script_data is None:
        if script_path and os.path.isfile(script_path):
            try:
                with open(script_path, "r", encoding="utf-8") as f:
                    script_data = json.load(f)
            except Exception as e:
                return {"ok": False, "skipped": False, "error": f"剧本文件读取失败: {e}"}
        else:
            return {"ok": False, "skipped": False, "error": "未提供有效的剧本数据或文件"}
    
    # 执行客观验证（不依赖AI）
    structure_issues = _validate_script_structure(script_data)
    logic_issues = _validate_script_logic(script_data)
    style_issues = _validate_script_style(script_data, style)
    prompt_issues = _validate_script_prompts(script_data)
    bloat_issues = _validate_script_bloat(script_data)
    feasibility_issues = _validate_script_feasibility(script_data, target_duration)
    # 92 镜拆解法五层软告警（2026-09-28 三层 + 2026-09-30 补 ④⑤）：剪辑动机覆盖率 /
    # 镜头语言克制分布 / 道具回环锚点 / 一镜一动作 / 主力景别区间。
    # 全部非 critical，进 prompt_quality 桶软扣分，不短路判失败。
    rhythm_issues = _validate_script_92rules(script_data)

    all_objective_issues = (
        structure_issues + logic_issues + style_issues +
        prompt_issues + bloat_issues + feasibility_issues + rhythm_issues
    )
    
    # 计算客观验证得分（每个问题扣5分，最低0分）
    objective_score = max(0, 100 - len(all_objective_issues) * 5)
    
    # 如果客观验证有严重问题（结构或逻辑错误），直接返回失败
    critical_issues = structure_issues + logic_issues
    if critical_issues:
        return {
            "ok": True,
            "passed": False,
            "score": min(objective_score, 50),
            "reason": f"客观验证发现{len(critical_issues)}个关键问题",
            "issues": all_objective_issues,
            "suggestions": ["修复结构和逻辑问题后重试"],
            "categories": {
                "structure": max(0, 100 - len(structure_issues) * 10),
                "logic": max(0, 100 - len(logic_issues) * 10),
                "style": max(0, 100 - len(style_issues) * 5),
                "prompt_quality": max(0, 100 - (len(prompt_issues) + len(bloat_issues)
                                                + len(rhythm_issues)) * 5),
                "feasibility": max(0, 100 - len(feasibility_issues) * 5)
            },
            "skipped": False,
            "objective_only": True,
        }
    
    # 调用AI进行深度质检
    prompt_template = cfg.get("script_prompt") or DEFAULT_SCRIPT_PROMPT
    script_json = json.dumps(script_data, ensure_ascii=False, indent=2)

    # ⚠️ 单镜时长口径**必须由 config 常量生成**（2026-10-02 修复）：
    #    这里曾硬编码「3-12 秒」，而生成端已按参考片重标定到 2~8 秒 →
    #    送检大模型拿到的合规区间与确定性校验（下面 _validate_script_92rules 用的
    #    SHOT_DURATION_MIN_OK/MAX_OK，同为 config 单一来源）**互相打架**：
    #    模型会放过 9-10 秒镜头、或把 2.5 秒镜头报成过短。
    #    改成占位符后，改 config 就自动同步，杜绝再次漂移。
    #    ⚠️ 用户若在配置里自定义了 script_prompt（旧文本仍含「3-12 秒」），
    #    replace 不会命中占位符 → 保持用户原文，属预期（用户口径优先）。
    # 台词预算（第 17 条）同样从 config 单一来源注入（2026-10-05）：旧文案写死
    # 「30 字（约 6.7 秒配音）」，而生成端台词预算（SHOT_SPEECH_BUDGET_CHARS，默认 16 字）
    # 早已收紧 —— 质检口径与生成端必须同源，改 config 即自动同步，杜绝再次漂移。
    # ⚠️ 与上面时长占位符同一机制：用户自定义的旧 script_prompt 不含该占位符 → 保持原文。
    speech_budget = getattr(config, "SHOT_SPEECH_BUDGET_CHARS", 16)
    prompt = prompt_template.replace(
        "{style}", style or "国漫古风"
    ).replace(
        "{target_duration}", str(target_duration)
    ).replace(
        "{shot_duration_min}", f"{SHOT_DURATION_MIN_OK:g}"
    ).replace(
        "{shot_duration_max}", f"{SHOT_DURATION_MAX_OK:g}"
    ).replace(
        "{shot_duration_silent}", f"{config.SHOT_DURATION_SILENT:g}"
    ).replace(
        "{speech_budget}", str(speech_budget)
    ).replace(
        "{script_data}", script_json[:8000]  # 限制长度，避免超出上下文
    )
    
    # 调用多模态模型（虽然剧本质检不需要图像，但复用现有接口）
    content = [{"type": "text", "text": prompt}]
    payload = {
        "model": ep["model"],
        "messages": [
            {"role": "system", "content": "你是严格、客观的漫剧剧本质检员，只输出JSON。"},
            {"role": "user", "content": content},
        ],
        "temperature": 0,
        "max_tokens": 1200,
        "stream": False,
    }
    
    t0 = time.time()
    try:
        resp = _post_chat(ep, payload, cfg.get("timeout", 180),
                          retries=cfg.get("api_retries", API_RETRY_ATTEMPTS),
                          backoff=cfg.get("api_backoff", API_RETRY_BACKOFF))
    except Exception as e:
        # AI调用失败，回退到客观验证结果
        logger.warning(f"剧本质检AI调用失败，使用客观验证结果：{e}")
        return {
            "ok": True,
            "passed": objective_score >= cfg.get("pass_score", 70),
            "score": objective_score,
            "reason": f"AI质检调用失败，基于客观验证（{len(all_objective_issues)}个问题）",
            "issues": all_objective_issues,
            "suggestions": [],
            "categories": {
                "structure": max(0, 100 - len(structure_issues) * 10),
                "logic": max(0, 100 - len(logic_issues) * 10),
                "style": max(0, 100 - len(style_issues) * 5),
                "prompt_quality": max(0, 100 - (len(prompt_issues) + len(bloat_issues)
                                                + len(rhythm_issues)) * 5),
                "feasibility": max(0, 100 - len(feasibility_issues) * 5)
            },
            "skipped": False,
            "ai_failed": True,
            "ai_error": str(e),
        }
    
    # 解析AI返回结果
    verdict = parse_verdict(resp["content"], cfg.get("pass_score", 70))
    
    # 合并客观验证和AI质检结果
    ai_issues = verdict.get("issues", [])
    ai_suggestions = verdict.get("suggestions", [])
    all_issues = all_objective_issues + ai_issues
    
    # 合并各维度得分
    categories = verdict.get("categories", {})
    objective_categories = {
        "structure": max(0, 100 - len(structure_issues) * 10),
        "logic": max(0, 100 - len(logic_issues) * 10),
        "style": max(0, 100 - len(style_issues) * 5),
        "prompt_quality": max(0, 100 - (len(prompt_issues) + len(bloat_issues)
                                        + len(rhythm_issues)) * 5),
        "feasibility": max(0, 100 - len(feasibility_issues) * 5)
    }
    
    # 取客观验证和AI质检的较低分
    for cat in ["structure", "logic", "style", "prompt_quality", "feasibility"]:
        obj_score = objective_categories.get(cat, 100)
        ai_score = categories.get(cat, 100)
        categories[cat] = min(obj_score, ai_score)
    
    # 计算加权综合分
    script_cats = cfg.get("script_categories", {})
    weighted_score = 0
    total_weight = 0
    for cat, score in categories.items():
        cat_config = script_cats.get(cat, {"weight": 0.2})
        weight = cat_config.get("weight", 0.2)
        weighted_score += score * weight
        total_weight += weight
    
    if total_weight > 0:
        final_score = int(weighted_score / total_weight)
    else:
        final_score = verdict.get("score", objective_score)
    
    # 合并关键缺陷
    critical_hits = find_critical_issues(all_issues)
    
    return {
        "ok": True,
        "passed": verdict.get("passed", False) and not critical_hits and final_score >= cfg.get("pass_score", 70),
        "score": final_score,
        "reason": verdict.get("reason", ""),
        "issues": all_issues[:20],  # 限制数量
        "suggestions": ai_suggestions[:10],
        "categories": categories,
        "critical_issues": critical_hits,
        "skipped": False,
        "latency_ms": resp.get("latency_ms"),
        "api_total_ms": int((time.time() - t0) * 1000),
        "objective_issues": {
            "structure": structure_issues,
            "logic": logic_issues,
            "style": style_issues,
            "prompt_quality": prompt_issues,
            "bloat": bloat_issues,
            "feasibility": feasibility_issues
        }
    }


