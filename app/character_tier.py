# -*- coding: utf-8 -*-
"""角色**级别**判定的叶子常量/判据（零重依赖，供音色链路、资产链路共用）。

为什么单独成模块
----------------
`asset_worker._character_tier` 能判定 `crowd`（群像），但它是**重模块**（会拉 ComfyUI 等）；
音色链路（`voice_bank` / `video_helpers`）也需要「这个角色是不是一群人」这个判据，却不宜
反向 import asset_worker。故把**群像标记词**与最简判据下沉到本叶子模块，单一事实源、两处复用。

与 `asset_worker` 的口径**同源**：强群像词命中即必然是一群人（集合名词）。
"""
from __future__ import annotations

#: 强群像词：命中即**必然是一群人**（集合名词）→ 直接判 crowd，优先于镜头/台词判定。
#: ⚠️ 与 asset_worker._CROWD_NAME_MARKERS 同源（那边改为 import 本常量，避免两处漂移）。
CROWD_NAME_MARKERS = (
    "群演", "群像", "围观", "路人", "群众", "众人", "人群", "人群们",
    "甲乙丙丁", "围观者", "群众演员", "龙套", "学生们", "士兵们", "弟子们",
    "们）", "们)", "众弟子", "众弟子们",
    # ⭐ 2026-10-20（用户实测「群像和之前不一样了」）：下面这几个词此前全部漏判 ——
    #   `外门弟子群` 不含 `群像`/`人群`，于是 is_crowd_name 返回 False，
    #   群像被当成普通单人角色 → 走三视图版式 → 画成「同一个人复制三份」，
    #   而质检又要求「单人物正面立绘」→ 三方打架、反复重试。
    "弟子群", "长老群", "师兄弟群", "弟子众", "众弟子们",
)

#: 弱群像词：可能是一群也可能单个（店员/侍卫/士兵…）——**本叶子模块不据此判 crowd**
#: （弱判定还需镜头/台词事实，属 asset_worker 的职责）；仅供需要时参考。
CROWD_WEAK_MARKERS = (
    "弟子", "侍卫", "侍从", "随从", "护卫", "士兵",
    "乘客", "行人", "店员", "服务员", "保安", "杂役", "学徒", "员工",
)


def is_crowd_name(name: str) -> bool:
    """名字是否是**集合名词/群像**（如「青云宗外门弟子群像」「围观路人」）→ 是一群人、不是一个人。

    仅据**强群像词**判定（确定性、零成本）；弱群像词（弟子/侍卫…）不在此判（需镜头事实）。
    """
    n = str(name or "")
    n = str(name or "")
    if any(m in n for m in CROWD_NAME_MARKERS):
        return True
    # ⭐ 2026-10-20：**后缀兜底** —— 3 字以上且以「群」结尾（外门弟子群 / 围观人群 / 守卫群）。
    #   两字名（如「王群」）不判，避免把真实人名误当群像。
    return len(n) >= 3 and n.endswith("群")
